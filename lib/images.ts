/**
 * Реестр изображений это единственное место, где меняется фотография.
 *
 * Каждый `id` соответствует части ссылки images.unsplash.com после «photo-»;
 * все проверены и отдают HTTP 200. Чтобы поставить сюда съёмку реальной
 * клиники, достаточно заменить id или направить `unsplashUrl` на свой CDN.
 * Больше ничего править не нужно.
 *
 * Правила отбора: холодно, тихо, архитектурно; живые лица при дневном свете;
 * никаких студийных улыбок крупным планом и ничего настолько клинического,
 * чтобы напугать тревожного читателя; цвет приглушён, чтобы кадр не спорил
 * с фоном `bone`.
 */

export type ImageAsset = {
  id: string;
  alt: string;
  /** CSS object-position. По умолчанию center. */
  focus?: string;
  /**
   * Дополнительные параметры imgix, приклеиваемые к ссылке: например, кадр
   * с фокусной точкой и зумом (`&crop=focalpoint&fp-y=…&fp-z=…`), когда
   * исходник снят слишком общо и его надо «поджать» до поясного портрета.
   * object-position такого не умеет: он двигает кадр, но не приближает.
   */
  params?: string;
  /**
   * «portrait» переводит снимок в тёплую монохромную обработку (см. утилиту
   * u-portrait-tone). Стоковые портреты сняты десятком разных фотографов, и
   * единая тональность превращает их в одну съёмку. Интерьеры и клинические
   * кадры остаются цветными.
   */
  tone?: "portrait";
};

export function unsplashUrl(id: string, width = 1600, quality = 72): string {
  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${width}&q=${quality}`;
}

