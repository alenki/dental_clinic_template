import type { ReactNode } from "react";

/**
 * Русская типографика переносов.
 *
 * По правилам русского набора короткие предлоги, союзы и частицы не оставляют
 * в конце строки: они уезжают на следующую вместе со своим словом. В крупном
 * кегле Playfair это видно особенно хорошо — строка «Что происходит и»
 * с одинокой «и» на конце читается как опечатка вёрстки.
 *
 * Разделитель перед коротким словом стоит в ретроспективной проверке, а не
 * в самом шаблоне, поэтому цепочки коротких слов («которым вы в любую»)
 * склеиваются за один проход: совпадение не съедает пробел, с которого должно
 * начаться следующее. Прежняя версия шаблоном захватывала разделитель, и
 * второе короткое слово цепочки оставалось неприклеенным, сколько проходов
 * ни делай.
 *
 * Кроме одно- и двухбуквенных слов приклеиваются трёхбуквенные предлоги:
 * повисшее «обдумываете без / спешки» — та же ошибка набора, что и «и» на
 * краю строки. Список именно предлогов: обычные трёхбуквенные слова («час»,
 * «год») переносятся как угодно.
 */
const SHORT_WORD =
  /(?<=^|[\s(«„—–-])([а-яёА-ЯЁ]{1,2}|[Бб]ез|[Дд]ля|[Пп]ри|[Нн]ад|[Пп]од|[Пп]ро|[Ии]зо|[Оо]то|[Оо]бо)\s+/g;

export function ru(text: string): string {
  return text.replace(SHORT_WORD, "$1 ");
}

/** То же самое, но безопасно для заголовков, которые приходят разметкой. */
export function ruNode(node: ReactNode): ReactNode {
  return typeof node === "string" ? ru(node) : node;
}
